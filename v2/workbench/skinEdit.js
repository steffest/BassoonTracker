// Pure text edits on a skin YAML buffer (spec 008).
//
// The workbench never rewrites a YAML document from a model: that would
// reformat the file and lose comments, which the save policy forbids. Setting
// a state's artwork therefore splices the exact scalar the compiler recorded
// a source range for, or inserts one line into the style's `states:` block at
// its own indentation. Everything here is a string in, string out, so it is
// tested in plain Node with no DOM and no editor.
//
// Offsets are the ones in the compiled skin, which the compiler computes on
// LF-normalized text - the same normalization the workbench applies to every
// buffer it holds.

/** Replaces `[range.start.offset, range.end.offset)` with `replacement`. */
export function replaceRange(text, range, replacement) {
    return text.slice(0, range.start.offset) + replacement + text.slice(range.end.offset);
}

/**
 * Refuses an edit whose source location no longer describes the buffer. A
 * range comes from the last generation; if the buffer has moved on (an
 * outline generated by an older compiler, an external edit, a dirty buffer
 * the caller failed to catch), splicing it would quietly corrupt the
 * document. Checking that the range still spans the text we expect turns
 * that into a refusal.
 */
function assertRangeStillHolds(text, range, expected, what) {
    const found = text.slice(range.start.offset, range.end.offset);
    if (found !== expected) {
        throw new Error(`stale source location for ${what}: line ${range.start.line} holds "${found}", not "${expected}". Save & Refresh to regenerate, then try again.`);
    }
}

const chr10 = String.fromCharCode(10);

function indentOf(column) {
    return " ".repeat(Math.max(column, 0));
}

/**
 * Sets the asset for one visual state of one style.
 *
 * - the style already declares that state itself: the asset name is replaced
 *   in place, so comments, order and formatting are untouched;
 * - the state is only inherited through `extends`, or absent: one line is
 *   inserted at the end of the style's own `states:` block, which overrides
 *   the inherited value;
 * - the style has no `states:` block at all: a two-line block is appended to
 *   the style.
 *
 * @param {string} text the whole buffer for the skin document
 * @param {object} style the compiled style (needs `states`, `statesSource`, `source`)
 * @param {string} state one of the STYLE_STATES names
 * @param {string} asset the asset (source PNG base) name
 * @returns {{ text: string, action: "replaced"|"inserted"|"created-block", line: number }}
 */
export function setStateAsset(text, style, state, asset) {
    const own = style.states && style.states[state];
    if (own && own.source && own.source.range && !own.inherited) {
        assertRangeStillHolds(text, own.source.range, own.asset, `${style.type}/${style.variant} ${state}`);
        return { text: replaceRange(text, own.source.range, asset), action: "replaced", line: own.source.range.start.line };
    }

    if (style.statesSource && style.statesSource.range) {
        const range = style.statesSource.range;
        // The block's own text cannot be compared to a known value, so check
        // the shape instead: the range must still end at the end of a
        // "key: value" line, which is where a new entry gets appended.
        const lastEntry = text.slice(range.start.offset, range.end.offset).split(chr10).pop();
        const after = text[range.end.offset];
        if (!/^\s*[A-Za-z_][\w]*:\s*\S/.test(lastEntry) || (after !== undefined && after !== chr10)) {
            throw new Error(`stale source location for the states block of ${style.type}/${style.variant}: line ${range.end.line} holds "${lastEntry}". Save & Refresh to regenerate, then try again.`);
        }
        const line = indentOf(range.start.column) + `${state}: ${asset}`;
        return { text: `${text.slice(0, range.end.offset)}\n${line}${text.slice(range.end.offset)}`, action: "inserted", line: range.end.line + 1 };
    }

    if (style.source && style.source.range) {
        // A style's own range starts at the indentation of its *properties*
        // (the mapping node, not the key line above it), so a new `states:`
        // key sits at exactly that column and its entry two further in.
        const range = style.source.range;
        const block = `\n${indentOf(range.start.column)}states:\n${indentOf(range.start.column + 2)}${state}: ${asset}`;
        return { text: `${text.slice(0, range.end.offset)}${block}${text.slice(range.end.offset)}`, action: "created-block", line: range.end.line + 2 };
    }

    throw new Error(`setStateAsset: ${state} on ${style.type}/${style.variant} has no source location to edit (built-in style?)`);
}

/**
 * Removes a style's own entry for one state, so it falls back to `extends` or
 * to the state chain again. Inherited and absent states are left alone.
 *
 * @returns {{ text: string, action: "removed"|"unchanged", line: number|null }}
 */
export function clearStateAsset(text, style, state) {
    const own = style.states && style.states[state];
    if (!own || own.inherited || !own.source || !own.source.range) return { text, action: "unchanged", line: null };
    assertRangeStillHolds(text, own.source.range, own.asset, `${style.type}/${style.variant} ${state}`);
    const offset = own.source.range.start.offset;
    let lineStart = text.lastIndexOf("\n", offset - 1) + 1;
    let lineEnd = text.indexOf("\n", own.source.range.end.offset);
    if (lineEnd === -1) lineEnd = text.length;
    else lineEnd += 1;
    return { text: text.slice(0, lineStart) + text.slice(lineEnd), action: "removed", line: own.source.range.start.line };
}
