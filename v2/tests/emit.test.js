test("disabledWhen is also generated for a module-owning container's own root, not only an inline child (spec 050)", () => {
    // A module-owning container (a plain panel, container.ownModule: true)
    // is not itself interactive and gets no controller, so authoring a rule
    // there alone has no runtime effect (confirmed empirically - see
    // design.md; sampleEditPanel.yaml's own real ftOnlyRow therefore
    // carries the rule on each interactive child instead, not on itself).
    // But the *generated code* for that shape must still be correct - spec
    // 025 already found and fixed the identical gap once for
    // breakpoints/visibleWhen ("two separate node-building code paths");
    // this is the same fix for highlightedWhen/disabledWhen, exercised here
    // directly against a hand-built tree since the real YAML no longer puts
    // a rule on a module-owning container's own root.
    const rootNode = {
        id: "root", type: "panel", definitionName: "root", labelVariants: ["root"],
        layout: {}, children: [], bindings: [{ kind: "visual-state", state: "disabled", mockField: "ft-mode.active", activeValue: true, conditionText: "ft mode", source: { file: "test.yaml", range: null } }],
        supported: true, source: { file: "test.yaml", range: null }, refSource: null
    };
    const compiled = { root: rootNode, skin: { styles: {}, source: null }, diagnostics: [], hardFailure: false, sourceFiles: [] };
    const emitted = emitApplication(compiled, { libraryBase: "..", capabilities: {} });
    const text = emitted.files.get("ui/main.js");
    assert.match(text, /disabledWhen: state => state\.get\("ft-mode\.active"\) !== true/);
});

test("generated state seeds command fields from the command's first mock value, not the visual-state fallback", async () => {
    const { INITIAL_STATE, createAppState } = await import(pathToFileURL(join(OUT, "state.js")).href);
    // Command fields first (their initial value is the command's first mock
    // value), then visual-state fallbacks, then fields a component binds
    // directly (spec 012's `field` on a label, which starts empty).
    assert.equal(INITIAL_STATE["playback.status"], "stopped", "the command's first mock value, not the rule's fallback");
    assert.equal(INITIAL_STATE["record.active"], false);
    assert.equal(INITIAL_STATE["song.title"], "", "a field-bound label makes its field part of the state");
    const state = createAppState();
    let changes = 0;
    state.onAnyChange(() => { changes += 1; });
    state.set("playback.status", "playing");
    state.set("playback.status", "playing");
    assert.equal(changes, 1, "onAnyChange fires once per actual change");
    assert.equal(state.get("playback.status"), "playing");
});

test("generated mock action toggles its state field and logs; the UI hook lazy-loads it", async () => {
    const { main } = await import(pathToFileURL(join(OUT, "ui/main.js")).href);
    const { createAppState } = await import(pathToFileURL(join(OUT, "state.js")).href);
    const play = flatten(main()).find(n => n.id === "main.controlBar.button.Play");
    const logged = [];
    const state = createAppState();
    const app = { state, log: (command, changes) => logged.push({ command, changes }), feature: async (load, run) => run(await load()) };
    // The dynamic import inside the hook is relative to ui/, resolved from the temp folder.
    await play.on.click(app);
    assert.equal(state.get("playback.status"), "playing");
    await play.on.click(app);
    assert.equal(state.get("playback.status"), "stopped");
    assert.deepEqual(logged.map(l => l.command), ["transport.toggle", "transport.toggle"]);
    assert.deepEqual(logged[0].changes, { "playback.status": "playing" });
});

test("a mapped capability replaces the mock with a delegating import", () => {
    const withCapability = emitApplication(compiled, {
        libraryBase: "..",
        capabilities: { "transport.toggle": { module: "./domain/transport.js", export: "togglePlay" } }
    });
    const action = withCapability.files.get("actions/transportToggle.js");
    assert.match(action, /import \{ togglePlay as implementation \} from "\.\.\/\.\.\/domain\/transport\.js"/);
    assert.match(action, /return implementation\(app, detail\)/);
    assert.ok(!/GENERATED MOCK/.test(action));
    assert.ok(!withCapability.looseEnds.some(e => e.kind === "mocked-command" && e.subject.includes("transport.toggle")));
    const mocked = list => list.filter(e => e.kind === "mocked-command").length;
    assert.equal(mocked(withCapability.looseEnds), mocked(emitted.looseEnds) - 1, "only the mapped command stops being listed as a mock");
});

test("a reserved host hook is wired into the app context, not into an action module", () => {
    const withHost = emitApplication(compiled, {
        libraryBase: "..",
        capabilities: { "host.openFiles": { module: "./domain/playback/index.js", export: "openFiles" } }
    });
    const main = withHost.files.get("main.js");
    assert.match(main, /openFiles: \(\.\.\.args\) => import\("\.\.\/domain\/playback\/index\.js"\)/, "imported on first use, so it stays out of the entry chunk");
    assert.match(main, /m\.openFiles\(app, \.\.\.args\)/);
    assert.match(main, /@property \{\(\.\.\.args: any\[\]\) => Promise<any>\} openFiles/, "and it is documented on the app context");
    // A host hook is not an authored command, so it gets no action module and
    // is never a loose end. Compared against the baseline action-file set
    // rather than matched by name, since an authored command's own derived
    // name (e.g. "loop-creator.open" -> "loopCreatorOpen.js") can coincide
    // with a host hook's name by accident.
    const actionFiles = files => [...files.keys()].filter(p => p.startsWith("actions/")).sort();
    assert.deepEqual(actionFiles(withHost.files), actionFiles(emitted.files), "a host hook adds no action module");
    assert.ok(!withHost.looseEnds.some(end => /host\./.test(end.subject || "")));

    const without = emitApplication(compiled, { libraryBase: ".." });
    assert.ok(!/openFiles/.test(without.files.get("main.js")), "an unmapped hook is simply absent");
});

