import { test, before, after } from "node:test";
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";
import { compileApplication } from "../compiler/convert.js";
import { emitApplication } from "../compiler/emit.js";

// The emitter is tested against the real YAML graph: files are written into a
// temporary folder (outside the repository, so cloud-sync locks cannot break
// cleanup) with an absolute file:// library base so their imports of the
// shared runtime still resolve, then imported and executed in Node (the UI
// factories and action modules are DOM-free; only mounting needs a browser).

const __dirname = dirname(fileURLToPath(import.meta.url));
const CURRENT = join(__dirname, "../project/specs/application/current");
const OUT = mkdtempSync(join(tmpdir(), "v2-emit-test-"));
const LIBRARY_BASE = pathToFileURL(join(__dirname, "..")).href;

function readSource(relPath) {
    try { return readFileSync(join(CURRENT, relPath), "utf8"); } catch { return null; }
}

let compiled, emitted;

before(() => {
    compiled = compileApplication("app.yaml", readSource);
    assert.equal(compiled.hardFailure, false);
    emitted = emitApplication(compiled, { libraryBase: LIBRARY_BASE, capabilities: {} });
    for (const [rel, text] of emitted.files) {
        mkdirSync(dirname(join(OUT, rel)), { recursive: true });
        writeFileSync(join(OUT, rel), text);
    }
});

after(() => rmSync(OUT, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 }));

function flatten(node, out = []) {
    out.push(node);
    (node.children || []).forEach(c => flatten(c, out));
    return out;
}

test("emits one UI module per authored container, one action per command, state, entry and documents", () => {
    // Asserted against the live YAML, so named modules must be *present*
    // rather than exhaustive: authoring a new container adds a module.
    const paths = [...emitted.files.keys()].sort();
    const uiPaths = paths.filter(p => p.startsWith("ui/"));
    for (const required of ["ui/controlBar.js", "ui/main.js", "ui/notifications.js", "ui/songProperties.js", "ui/infoBar.js", "ui/editPad.js", "ui/optionsPanel.js", "ui/songPatternList.js", "ui/top.js"]) assert.ok(uiPaths.includes(required), required);
    const panels = flatten(compiled.root).filter(n => n.type === "panel" && n.supported !== false);
    assert.equal(uiPaths.length, panels.length, "one UI module per supported authored panel");
    const actionPaths = paths.filter(p => p.startsWith("actions/"));
    assert.ok(actionPaths.includes("actions/transportToggle.js"));
    assert.equal(actionPaths.length, emitted.actions.length, "one module per resolved command");
    for (const required of ["main.js", "state.js", "config.js", "skin.js", "index.html", "README.md", "LOOSE-ENDS.md", ".generated"]) assert.ok(paths.includes(required), required);
    for (const [rel, text] of emitted.files) if (rel.endsWith(".js")) assert.match(text, /GENERATED by `node v2\/build\.mjs`/, rel);
});

test("generated UI builds the same tree as the outline minus unsupported nodes, with behavior as functions", async () => {
    const { main } = await import(pathToFileURL(join(OUT, "ui/main.js")).href);
    const root = main();
    const ids = flatten(root).map(n => n.id);
    const outlineSupported = flatten(compiled.root).filter(n => n.supported !== false).map(n => n.id);
    assert.deepEqual(ids, outlineSupported, "same ids in the same order, unsupported nodes omitted");
    assert.ok(!ids.some(id => /volume meter|notification light/.test(id)), "placeholders are gone");
    assert.ok(ids.some(id => id === "main.top.menu"), "menu is implemented as of spec 023, so it is rendered now");
    const play = flatten(root).find(n => n.id === "main.controlBar.button.Play");
    assert.equal(typeof play.highlightedWhen, "function");
    // Spec 014: one hook per authored event, so a `change` action can no
    // longer end up on the click hook.
    assert.equal(typeof play.on.click, "function");
    assert.equal(play.highlightedWhen({ get: f => (f === "playback.status" ? "playing" : null) }), true);
    assert.equal(play.highlightedWhen({ get: () => "stopped" }), false);
    assert.deepEqual(play.labelVariants, ["Play"]);
    assert.equal(play.shortKey, "Enter");
    const song = flatten(root).find(n => n.id === "main.controlBar.radioGroup.song");
    assert.deepEqual(song.labelVariants.map(v => v.toLowerCase()), ["song", "s"]);
    assert.equal(song.on, undefined, "no action bound: inert radio item");
    // The radio group, not the item, is where the group's change action lives.
    const group = flatten(root).find(n => n.id === "main.controlBar.radioGroup");
    assert.equal(typeof group.on.change, "function", "a change action reaches the group as a change hook");
    // And a value control carries its declared bounds through generically.
    const tracks = flatten(root).find(n => n.type === "spinBox");
    assert.ok(tracks, "the authored spin box is rendered now that it is implemented");
    const controlBar = flatten(root).find(n => n.id === "main.controlBar");
    assert.deepEqual(controlBar.layout, { width: { mode: "fill" }, height: { mode: "fixed", size: 28 } });
    assert.deepEqual(flatten(root).find(n => n.id === "main.normalMainView.songProperties").layout, { width: { mode: "fill" }, height: { mode: "fixed", size: 220 }, direction: "column", resizable: "horizontal" });
    // Spec 025: controlBar owns its own UI module (a panel with children),
    // and its breakpoints must survive that path too, not only an inline
    // child's (emit.js has two separate node-building code paths).
    assert.deepEqual(controlBar.breakpoints, [{ maxWidth: 650, layout: { height: { mode: "fixed", size: 160 }, direction: "column" } }]);
    const optionsPanel = flatten(root).find(n => n.id === "main.normalMainView.songProperties.optionsPanel");
    assert.deepEqual(optionsPanel.visibleWhen, { field: "song-properties-view.value", oneOf: ["Options"] });
});

