test("loose ends cover every warning once and say what the build did", () => {
    // Counts are lower bounds: the authored application grows, the mapping
    // from a warning to a loose-end kind is what this pins down.
    const kinds = emitted.looseEnds.map(e => e.kind);
    assert.ok(kinds.filter(k => k === "unsupported-node").length >= 2, "the two notification lights (menu is implemented as of spec 023, volume meter as of spec 054)");
    assert.ok(kinds.filter(k => k === "mocked-command").length >= 1);
    assert.ok(kinds.filter(k => k === "inert-control").length >= 2);
    assert.ok(kinds.filter(k => k === "unresolved-rule").length >= 2);
    assert.ok(kinds.filter(k => k === "unresolved-action-reference").length >= 2);
    assert.equal(kinds.filter(k => k === "unsupported-component").length, 0, "covered by the omitted-node entries");
    assert.equal(kinds.filter(k => k === "unresolved-component-reference").length, 0, "covered by the omitted-node entries");
    assert.ok(kinds.filter(k => k === "empty-container").length >= 1, "notifications lost both children");
    for (const e of emitted.looseEnds) {
        assert.match(e.where, /\.yaml:\d+$/, "every loose end points at a source line");
        assert.ok(e.did.length > 0);
    }
    const md = emitted.files.get("LOOSE-ENDS.md");
    assert.match(md, new RegExp(`${emitted.looseEnds.length} item\\(s\\)`));
    const rows = (md.match(/^\| [a-z-]+ \|/gm) || []).filter(r => !r.startsWith("| kind |"));
    assert.equal(rows.length, emitted.looseEnds.length);
});

test("emits the compiled skin in atlas mode and links every styled node to its variant", async () => {
    const skinModule = emitted.files.get("skin.js");
    assert.match(skinModule, /GENERATED by/);
    const { SKIN } = await import(pathToFileURL(join(OUT, "skin.js")).href);
    assert.equal(SKIN.mode, "atlas", "a release always loads the packed atlas, never the loose PNGs");
    assert.equal(SKIN.name, compiled.skin.name);
    // Authoring-only source ranges are stripped; the trace from an asset to
    // its source PNG survives.
    assert.ok(!/"statesSource"/.test(skinModule) && !/"usedBy"/.test(skinModule));
    assert.ok(SKIN.assets.length > 0);
    for (const asset of SKIN.assets) assert.match(asset.file, /^src\/.+\.png$/);
    assert.ok(SKIN.styles.button.play, "the play variant is part of the release skin");
    assert.equal(SKIN.styles.button.play.states.normal.asset, compiled.skin.styles.button.play.states.normal.asset);

    const { main } = await import(pathToFileURL(join(OUT, "ui/main.js")).href);
    const nodes = flatten(main());
    const play = nodes.find(n => n.id === "main.controlBar.button.Play");
    assert.deepEqual(play.style, { type: "button", variant: "play" });
    const panel = nodes.find(n => n.type === "panel");
    assert.deepEqual(panel.style, { type: "panel", variant: "default" }, "an unstyled node still resolves to default");
    assert.match(emitted.files.get("ui/controlBar.js"), /style: "play"/);
});

