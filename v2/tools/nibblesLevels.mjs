#!/usr/bin/env node
// Nibbles level extraction (spec 047). Development-time tool, Node only:
// v1's own `getLevelSprite()` (script/plugins/games/nibbles/nibbles.js:557-575)
// decodes a 206x97 indexed PNG spritesheet at *runtime*, one 40x15 tile per
// level (30 levels, 6 rows of 5), reading pixel colors with a real canvas
// 2D context - a magenta pixel (255,0,255) is the snake's own start point,
// any other non-black pixel is a wall, colored for visual variety only.
//
// v2 has no reason to keep that runtime decode: the level layouts are fixed
// data, never swapped at dev time the way a skin PNG can be (spec 008's own
// atlas stays swappable on purpose; these levels do not need to be). This
// tool reuses `decodePng()` from tools/skinAtlas.mjs (already a general
// 8-bit, non-interlaced, indexed-or-RGBA PNG reader) to decode the same
// source PNG once, and writes the result as a plain ES module -
// `domain/nibbles/levels.js` - imported directly, synchronously, headless-
// testable with no fetch and no canvas.
//
//   node v2/tools/nibblesLevels.mjs   regenerate domain/nibbles/levels.js
//
// Not run by `build.mjs` - the output is a checked-in source file, the same
// footing as domain/playback/engine/enum.js's own big NOTEPERIOD/FTNOTEPERIOD
// data tables, regenerated only if the source PNG ever changes.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { decodePng } from "./skinAtlas.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const SOURCE = join(__dirname, "..", "assets", "games", "nibbles", "src", "levels.png");
const OUT = join(__dirname, "..", "domain", "nibbles", "levels.js");

const TILE_WIDTH = 40;
const TILE_HEIGHT = 15;
const COLUMNS = 5;
const LEVEL_COUNT = 30;
const START_COLOR = [255, 0, 255];

/** One level: a start point plus a sparse list of wall cells, each pointing at a small per-level color palette (matching v1's own per-level `colorMap`/`colors`, built fresh per level rather than one global table). */
function extractLevel(image, levelIndex) {
    const row = Math.floor((levelIndex - 1) / COLUMNS);
    const col = (levelIndex - 1) - row * COLUMNS;
    const originX = 1 + col * (TILE_WIDTH + 1);
    const originY = 1 + row * (TILE_HEIGHT + 1);

    let start = null;
    const colors = [];
    const colorIndex = new Map();
    const cells = [];

    for (let y = 0; y < TILE_HEIGHT; y++) {
        for (let x = 0; x < TILE_WIDTH; x++) {
            const sx = originX + x, sy = originY + y;
            const offset = (sy * image.width + sx) * 4;
            const r = image.data[offset], g = image.data[offset + 1], b = image.data[offset + 2];
            if (r === START_COLOR[0] && g === START_COLOR[1] && b === START_COLOR[2]) {
                start = { x, y };
            } else if (r > 0 || g > 0 || b > 0) {
                const key = `${r},${g},${b}`;
                let index = colorIndex.get(key);
                if (index === undefined) {
                    index = colors.length;
                    colorIndex.set(key, index);
                    colors.push(key);
                }
                cells.push([x, y, index]);
            }
        }
    }

    if (!start) throw new Error(`level ${levelIndex}: no start point found (matches nibbles.js's own warning path, ported as a hard failure here since this tool runs once, offline, over known-good source art)`);
    return { start, colors, cells };
}

function run() {
    const image = decodePng(SOURCE);
    const levels = [];
    for (let level = 1; level <= LEVEL_COUNT; level++) levels.push(extractLevel(image, level));

    const body = levels.map(level => {
        const cells = level.cells.map(([x, y, c]) => `[${x},${y},${c}]`).join(",");
        const colors = level.colors.map(c => JSON.stringify(c)).join(",");
        return `    { start: { x: ${level.start.x}, y: ${level.start.y} }, colors: [${colors}], cells: [${cells}] }`;
    }).join(",\n");

    const source = `// GENERATED by tools/nibblesLevels.mjs from assets/games/nibbles/src/levels.png.
// Do not edit by hand: change the source PNG and regenerate.
//
// One entry per level (1-indexed levels, 0-indexed array), each a fixed
// ${TILE_WIDTH}x${TILE_HEIGHT} grid (domain/nibbles/index.js's own GRID_WIDTH/
// GRID_HEIGHT): a snake start point, a small per-level color palette, and a
// sparse [x, y, colorIndex] wall-cell list (everything not listed is open
// floor). Ported from script/plugins/games/nibbles/nibbles.js's own
// getLevelSprite()/setLevel() (403-446, 557-575).

export const LEVELS = [
${body}
];
`;
    writeFileSync(OUT, source);
    console.log(`nibblesLevels: wrote ${OUT} (${levels.length} levels)`);
}

run();
