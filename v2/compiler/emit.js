import { EXTRA_LAYOUT_FIELDS } from "./layoutFields.js";
// Emits the compiled application as readable JavaScript modules (spec 007,
// "release build"). Input: the tree + diagnostics compileApplication()
// returns. Output: a map of relative file paths to file contents for the
// `app/` folder: one UI module per authored container, one action module per
// command (a lazy-loaded feature), a state module, an entry, and two
// generated documents (README.md, LOOSE-ENDS.md).
//
// Policy decided 2026-09-10: unresolved warnings never fail the build. Every
// unsupported or unresolved node is left out of the emitted UI (or becomes a
// no-op) and is listed in LOOSE-ENDS.md with what the build did about it.
//
// The emitter writes code, not data: nothing here is evaluated at build
// time, and generated modules import the shared runtime library rather than
// duplicating it.

import { COMPILER_VERSION } from "./convert.js";
import { ownsModule, isContainer, selectionModeOf, behaviorOf, componentType } from "../runtime/componentTypes.js";
import { boundsOf, valueFieldOf } from "../runtime/valueController.js";
import { scrollFieldOf } from "../runtime/listController.js";
import { rowsFieldOf } from "../runtime/fileBrowserController.js";

/** A manifest key with this prefix is a host hook, not an authored command. */
const HOST_PREFIX = "host.";

const GENERATED_HEADER = "GENERATED by `node v2/build.mjs` from the YAML under project/specs/application/current. Do not edit: change the YAML and rebuild.";

// Strips the authoring-only source ranges from a compiled skin and switches
// it to atlas mode, which is the only mode a release uses.
function releaseSkinModel(skin) {
    const source = skin || {};
    const strip = value => {
        if (Array.isArray(value)) return value.map(strip);
        if (value && typeof value === "object") {
            return Object.fromEntries(Object.entries(value)
                .filter(([key]) => !["source", "statesSource", "usedBy"].includes(key))
                .map(([key, entry]) => [key, strip(entry)]));
        }
        return value;
    };
    return { ...strip(source), mode: "atlas" };
}

function identifier(text, fallback = "node") {
    const cleaned = String(text || "")
        .replace(/[^A-Za-z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ""))
        .replace(/^[^A-Za-z_]+/, "");
    const id = cleaned ? cleaned[0].toLowerCase() + cleaned.slice(1) : fallback;
    return RESERVED.has(id) ? `${id}Component` : id;
}
const RESERVED = new Set(["default", "import", "export", "class", "function", "return", "new", "var", "let", "const", "if", "else", "switch", "case", "for", "while", "do", "break", "continue", "this", "super", "null", "true", "false", "in", "of", "delete", "typeof", "void", "with", "yield", "await", "async", "static", "extends", "enum", "package", "private", "protected", "public", "interface", "implements", "try", "catch", "finally", "throw", "debugger", "instanceof"]);

function js(value) {
    return JSON.stringify(value);
}

function labelLiteral(node) {
    return js(node.labelVariants.join(", "));
}

// Plain-object literal with unquoted keys, for readable generated code.
function obj(value) {
    if (Array.isArray(value)) return `[${value.map(obj).join(", ")}]`;
    if (value && typeof value === "object") return `{ ${Object.entries(value).map(([k, v]) => `${/^[A-Za-z_$][\w$]*$/.test(k) ? k : js(k)}: ${obj(v)}`).join(", ")} }`;
    return js(value);
}

function layoutLiteral(layout) {
    const parts = [];
    if (layout.width && layout.width.mode !== "auto") parts.push(`width: ${obj(layout.width)}`);
    if (layout.height && layout.height.mode !== "auto") parts.push(`height: ${obj(layout.height)}`);
    if (layout.direction) parts.push(`direction: ${js(layout.direction)}`);
    if (layout.resizable) parts.push(`resizable: ${js(layout.resizable)}`);
    for (const key of EXTRA_LAYOUT_FIELDS) if (layout[key] !== undefined) parts.push(`${key}: ${js(layout[key])}`);
    return parts.length ? `layout: { ${parts.join(", ")} }` : null;
}

// Import prefix for the shared library from a file `depth` folders below the
// app root. `libraryBase` is normally a relative path ("..") but may be an
// absolute URL (tests emit into a temp folder outside the tree).
function upDirs(depth, libraryBase) {
    const base = libraryBase.replace(/\/?$/, "/");
    return /^[a-z]+:\/\//i.test(base) ? base : "../".repeat(depth) + base;
}

/**
 * @param {{ root: object, diagnostics: object[], sourceFiles: Iterable<string>, sourceHash?: string }} compiled
 * @param {{ capabilities?: Record<string, { module: string, export: string }>, libraryBase?: string }} [options]
 *   `libraryBase` is the path from the app folder to the v2 root (default "..").
 *   `capabilities` maps a command id to a hand-written module (path relative
 *   to the v2 root) and export; unmapped commands get a generated mock.
 * @returns {{ files: Map<string, string>, looseEnds: object[], actions: object[], uiModules: string[] }}
 */
export function emitApplication(compiled, options = {}) {
    const libraryBase = options.libraryBase || "..";
    const capabilities = options.capabilities || {};
    // Spec 014: a `host.` key in the manifest is not a compiled command. It
    // is a hook the renderer offers the application (a file drop, so far),
    // and it is wired into the app context rather than into an action module.
    const hostHooks = Object.entries(capabilities)
        .filter(([command]) => command.startsWith(HOST_PREFIX))
        .map(([command, capability]) => ({ name: command.slice(HOST_PREFIX.length), command, capability }));
    const files = new Map();
    const looseEnds = [];
    const actions = new Map(); // command -> { command, moduleName, exportName, binding, capability }
    const stateFields = new Map(); // field -> initial value (command bindings first)
    const visualFallbacks = new Map(); // field -> fallback when no command drives it
    const uiModules = new Map(); // node.id -> { moduleName, exportName, node }
    const usedModuleNames = new Set(["main"]);

    function unique(base) {
        let name = base;
        let n = 2;
        while (usedModuleNames.has(name)) name = `${base}${n++}`;
        usedModuleNames.add(name);
        return name;
    }

    // --- pass 1: classify -------------------------------------------------
    function visit(node, isRoot) {
        if (node.supported === false) {
            looseEnds.push({
                kind: "unsupported-node",
                subject: `${node.type} "${node.labelVariants[0] || node.definitionName || node.id}"`,
                where: `${node.source.file}:${node.source.range?.start.line ?? "?"}`,
                did: "not rendered (node omitted from the generated UI)"
            });
            return;
        }
        if (ownsModule(node.type)) {
            const moduleName = isRoot ? "main" : unique(identifier(node.definitionName || node.labelVariants[0] || node.id));
            uiModules.set(node.id, { moduleName, exportName: moduleName, node });
        }
        // A field-bound node makes that field part of the application's state,
        // so a capability has somewhere to publish to (spec 012). A control
        // whose field holds a *number* needs a numeric initial value, and a
        // value control resolves its field the same way the renderer does, so
        // the field the store declares is the field the renderer writes
        // (spec 014).
        const behavior = behaviorOf(node.type);
        if (behavior === "value") {
            const field = valueFieldOf(node);
            if (field && !stateFields.has(field)) stateFields.set(field, boundsOf(node).min);
        } else if (behavior === "scroll") {
            if (node.field && !stateFields.has(node.field)) stateFields.set(node.field, 0);
        } else if (behavior === "list") {
            // Two fields (spec 019): the selection, resolved exactly as a
            // value control's is, and the scroll offset, which is never
            // authored - only the derived name exists, so scrolling a list
            // can never disturb its selection.
            const field = valueFieldOf(node);
            if (field && !stateFields.has(field)) stateFields.set(field, 0);
            const scrollField = scrollFieldOf(node);
            if (scrollField && !stateFields.has(scrollField)) stateFields.set(scrollField, 0);
        } else if (behavior === "rowList") {
            // A fileBrowser's own rows are never authored (spec 035) - a
            // domain capability publishes them at runtime the way a value
            // control's field is written, so nothing seeds them without this
            // case. Confirmed missing: neither "rows.<id>" nor its own
            // scroll field (reusing listController.js's scrollFieldOf
            // unchanged, exactly as runtime/fileBrowserController.js's own
            // header comment already documents) was ever registered here,
            // so every domain/diskOperations#publish() call has been
            // throwing "store: unknown field" in the real generated
            // application since this type was first built (spec 035/036) -
            // invisible until now because every existing test's own fake
            // app.state stands in for the store with no field validation at
            // all, unlike the real one (runtime/store.js#set/subscribe).
            const rowsField = rowsFieldOf(node);
            if (rowsField && !stateFields.has(rowsField)) stateFields.set(rowsField, []);
            const scrollField = scrollFieldOf(node);
            if (scrollField && !stateFields.has(scrollField)) stateFields.set(scrollField, 0);
            // Spec 071: a fileBrowser with no `change` action at all (none
            // exist yet, but nothing forbids one) would still read its own
            // selection through valueFieldOf()'s id-derived fallback
            // ("value.<id>"), same as "list"'s selection a few cases up -
            // declared here so that case is not a second, quieter version of
            // the rows/scroll gap just above. This is *not* what fixes a
            // fileBrowser that does have a `change` action bound (every real
            // one so far does): see the field-prop emission below, which is
            // the actual fix for the live bug this spec found. Seeded to -1
            // ("no row selected"), not 0 as "list" seeds its own field - a
            // fileBrowser's rows start empty and are populated later by a
            // capability, unlike a listbox's fixed, always-non-empty,
            // YAML-authored items.
            const field = valueFieldOf(node);
            if (field && !stateFields.has(field)) stateFields.set(field, -1);
        } else if (behavior === "disclose") {
            // A dropdown's own field holds a numeric index, exactly like a
            // listbox's (spec 020). Its popup's own field is the *same* name
            // (runtime/overlaySynthesis.js sets both explicitly), so seeding
            // this one covers both; the popup's own scroll field is a
            // mount-time-only concern (the popup itself is synthesized, never
            // compiled) and is not declared here - a generated application's
            // popup scrolling falls back to the same undeclared-field
            // tolerance setField() already has, and is recorded as a known
            // gap in design.md.
            const field = valueFieldOf(node);
            if (field && !stateFields.has(field)) stateFields.set(field, 0);
        } else if (behavior === "tabs") {
            // A tabPanel's own field holds the active index, resolved exactly
            // as listbox's selection is (spec 021).
            const field = valueFieldOf(node);
            if (field && !stateFields.has(field)) stateFields.set(field, 0);
        } else if (behavior === "collapsible") {
            // A collapsePanel's own field is boolean, not numeric (spec 021):
            // truthy hides its content, so an unwritten field reads as
            // "not collapsed", matching v1's own always-showing behaviour.
            const field = valueFieldOf(node);
            if (field && !stateFields.has(field)) stateFields.set(field, false);
        } else if (behavior === "digitEntry") {
            // numberDisplay's own field holds a plain number, seeded to its
            // own minimum bound exactly as a slider's is (spec 027) - never
            // snapped to a step grid, since nothing about this control's own
            // editing is.
            const field = valueFieldOf(node);
            if (field && !stateFields.has(field)) stateFields.set(field, boundsOf(node).min);
        } else if (node.field && !stateFields.has(node.field)) {
            stateFields.set(node.field, "");
        }
        // Spec 025: a `visibleWhen.field` is shared by however many nodes
        // gate their own visibility on it, so no single one of them owns its
        // starting value - seeded to "", matching a plain field-bound
        // label's own default (spec 012), so nothing matches until an
        // authored action (or a generated app's own code) writes it.
        if (node.visibleWhen && node.visibleWhen.field && !stateFields.has(node.visibleWhen.field)) {
            stateFields.set(node.visibleWhen.field, "");
        }
        for (const binding of node.bindings || []) {
            if (binding.origin === "action" && binding.kind === "command") {
                if (!actions.has(binding.command)) {
                    const moduleName = identifier(binding.command);
                    const capability = capabilities[binding.command] || null;
                    actions.set(binding.command, { command: binding.command, moduleName, exportName: moduleName, binding, capability, users: [] });
                    if (binding.mockField && !stateFields.has(binding.mockField)) {
                        // A command whose value comes from the gesture has no
                        // values to cycle, but it still needs its field to
                        // exist before the first write (spec 014).
                        //
                        // Spec 098: when the gesture that writes it is an
                        // exclusive choice (a radio group's own items - read
                        // from the child type's declared `selection`, never
                        // from a type name), the field starts on the first
                        // choice rather than on "", which matches no choice
                        // at all and leaves the group drawn with nothing lit.
                        // v1 has no such state: every option group resolves
                        // an index through its own getValue() on first
                        // layout. A persisted setting (domain/settings#
                        // applyPersistedSettings) still overrides this at
                        // store construction, so it only decides what a field
                        // with no stored value shows.
                        const values = Array.isArray(binding.mockValues) ? binding.mockValues : [];
                        const firstChild = (node.children || [])[0];
                        const exclusive = firstChild && componentType(firstChild.type)?.selection === "exclusiveWithinParent";
                        const firstChoice = exclusive ? (firstChild.definitionName || (firstChild.labelVariants || [])[0] || "") : "";
                        stateFields.set(binding.mockField, values.length ? values[0] : firstChoice);
                    }
                    if (!capability) {
                        looseEnds.push({
                            kind: "mocked-command",
                            subject: `command ${binding.command}`,
                            where: `${binding.source.file}:${binding.source.range?.start.line ?? "?"}`,
                            did: `no capability module mapped in capabilities.js; actions/${moduleName}.js is a GENERATED MOCK that toggles ${binding.mockField || "nothing"}`
                        });
                    }
                }
                actions.get(binding.command).users.push(node.id);
            }
            if (binding.kind === "visual-state" && binding.mockField && !visualFallbacks.has(binding.mockField)) {
                visualFallbacks.set(binding.mockField, typeof binding.activeValue === "boolean" ? false : null);
            }
        }
        if (selectionModeOf(node.type) === "exclusiveWithinParent" && !(node.bindings || []).some(b => b.origin === "action")) {
            looseEnds.push({
                kind: "inert-control",
                subject: `${node.type} "${node.labelVariants[0]}"`,
                where: `${node.source.file}:${node.source.range?.start.line ?? "?"}`,
                did: "selectable (UI state only); no command is dispatched"
            });
        }
        node.children.forEach(child => visit(child, false));
        if (isContainer(node.type) && node.children.length > 0 && node.children.every(child => child.supported === false)) {
            looseEnds.push({
                kind: "empty-container",
                subject: `panel "${node.definitionName || node.id}" lost all of its children`,
                where: `${node.source.file}:${node.source.range?.start.line ?? "?"}`,
                did: "rendered as an empty panel (its authored children are unsupported)"
            });
        }
    }
    visit(compiled.root, true);
    for (const [field, fallback] of visualFallbacks) if (!stateFields.has(field)) stateFields.set(field, fallback);

    for (const d of compiled.diagnostics) {
        if (d.severity !== "warning") continue;
        const where = `${d.file}:${d.range?.start.line ?? "?"}`;
        // A node already listed as omitted covers the compiler's own
        // "unsupported"/"unresolved reference" warning for the same source line.
        if ((d.code === "unsupported-component" || d.code === "unresolved-component-reference") && looseEnds.some(e => e.kind === "unsupported-node" && e.where === where)) continue;
        const did = d.code === "unresolved-action-reference" || d.code === "unresolved-action" ? "activation is a no-op"
            : d.code === "unresolved-rule" ? "rule has no effect"
            : d.code === "unresolved-component-reference" || d.code === "unsupported-component" ? "not rendered"
            : d.code === "ambiguous-duplicate-name" ? "identities suffixed #1..#n"
            : "no effect";
        looseEnds.push({ kind: d.code, diagnosticCode: d.code, subject: d.message, where, did });
    }

    // --- pass 2: emit UI modules ----------------------------------------
    function nodeExpression(node, depth, indent, moduleImports) {
        const pad = "    ".repeat(indent);
        if (node.supported === false) {
            return { comment: `${pad}// ${node.type} "${node.labelVariants[0] || node.definitionName}" (${node.source.file}:${node.source.range?.start.line ?? "?"}) is not rendered: unsupported component. See LOOSE-ENDS.md.` };
        }
        if (ownsModule(node.type) && uiModules.has(node.id) && depth > 0) {
            const mod = uiModules.get(node.id);
            moduleImports.add(mod.moduleName);
            return { expr: `${pad}${mod.exportName}()` };
        }
        const comments = [];
        const props = [`id: ${js(node.id)}`];
        if (node.definitionName) props.push(`name: ${js(node.definitionName)}`);
        if (node.labelVariants.length && !(node.definitionName && node.labelVariants.length === 1 && node.labelVariants[0] === node.definitionName)) {
            props.push(`label: ${labelLiteral(node)}`);
        } else if (!node.labelVariants.length && node.definitionName) {
            // Spec 071: labelVariants is empty here *only* because `label: ""`
            // was authored explicitly - compiler/convert.js#applyLabel already
            // falls back to the node's own name for "no label authored at
            // all," baking that into a non-empty labelVariants at compile
            // time, so an empty array reaching this point with a real name
            // can only mean a deliberate, explicit override. Without emitting
            // `label: []` here, runtime/components.js#component()'s own
            // `props.label` would be `undefined` (the prop omitted entirely),
            // and its own labelVariants(undefined, props.name) falls back to
            // props.name regardless - silently overriding the compiler's own
            // decision (found placing this application's first image-only
            // button, logoBanner - v1's own logo has no text on it at all,
            // but its own bare authored name rendered on top of the artwork).
            props.push("label: []");
        }
        const layout = layoutLiteral(node.layout || {});
        if (layout) props.push(layout);
        if (node.style && node.style.variant && node.style.variant !== "default") {
            const at = node.style.definition ? `${node.style.definition.file}:${node.style.definition.range?.start.line ?? "?"}` : "the skin";
            comments.push(`style -> ${node.style.type}/${node.style.variant} (${at})`);
            props.push(`style: ${js(node.style.variant)}`);
        }
        if (node.field) {
            props.push(`field: ${js(node.field)}`);
        } else if (["rowList", "tabs", "text"].includes(behaviorOf(node.type))) {
            // Spec 071: valueFieldOf(node) (runtime/valueController.js) is
            // supposed to be one function both compile time and runtime
            // agree on, but its second resolution step - a `change` action's
            // own recipe-derived mockField - reads node.bindings, which this
            // very function's own node carries at compile time but
            // runtime/components.js#component() never puts on the tree it
            // builds from generated code. So a fileBrowser authored with a
            // `change` action but no explicit `field:` (instrumentList,
            // songPatternList's list) compiled its state field as e.g.
            // "instrument-row.value" (found via the binding) while
            // mountGeneric.js's own valueFieldOf(runtimeNode) call - same
            // function, no bindings to find - fell through to step three,
            // "value.<id>", a field nothing ever declared. Every real
            // pointerup on such a row threw "state field ... is not
            // declared" and silently dropped the write (caught live
            // double-clicking spec 071's instrument list; no existing test
            // caught it because a domain test dispatches its capability
            // directly with an explicit `detail.value`, never touching
            // mountGeneric.js's own store write at all). Emitting the
            // compile-time-resolved name explicitly as `field` is what every
            // other authored value control already does implicitly, once it
            // has *any* explicit `field:` of its own; a fileBrowser relying
            // solely on its `change` action's derived name was the one
            // case that never got one.
            //
            // Spec 072 found the identical gap a second time, for "tabs"
            // (patternSidebar.yaml's own tabPanel, authored with a `change`
            // action and no explicit `field:` either) - confirmed by reading
            // the compiled node directly (bindings resolve "sidebar-tab.value",
            // the runtime fallback would have been "value.<id>") before
            // fixing, not assumed from the rowList case alone.
            //
            // Spec 073 found it a third time, for "text" (patternSidebar.yaml's
            // own sample-search inputbox, authored with a `change` action and
            // no explicit `field:` - every other authored inputbox in this app
            // reuses an existing domain field, e.g. modNameInput's own
            // `field: song.title`, which is why none of them hit this before).
            // Without a runtime `node.field`, mountGeneric.js's own textOf()
            // falls back to labelText(node) - the node's own bare name,
            // "sampleSearchBox" - instead of ever reading the (empty) bound
            // field, so the draw kind's own `if (label) ... else if
            // (node.placeholder)` branch never reached the placeholder at
            // all; found live (the search box showed "SAMPLESEARCHBOX"
            // instead of "Search"). "disclose"/"collapsible"/"digitEntry"/
            // "list" share the same theoretical gap in principle (all
            // read/write through valueFieldOf too), but every existing
            // author of those happens to give an explicit `field:` already,
            // so there is no fourth *confirmed* case to fix yet - recorded
            // here rather than generalized on a guess.
            const derivedField = valueFieldOf(node);
            if (derivedField) props.push(`field: ${js(derivedField)}`);
        }
        if (node.shortKey) props.push(`shortKey: ${js(node.shortKey)}`);
        if (node.tooltip) props.push(`tooltip: ${js(node.tooltip)}`);
        if (node.labelMinWidths) props.push(`labelMinWidths: ${js(node.labelMinWidths)}`);
        if (node.color) props.push(`color: ${js(node.color)}`);
        // Spec 025: both are plain data, so the same JSON literal the compiler
        // itself built for `runtime/genericLayout.js` reaches the generated
        // application's own tree unchanged.
        if (node.breakpoints) props.push(`breakpoints: ${js(node.breakpoints)}`);
        if (node.visibleWhen) props.push(`visibleWhen: ${js(node.visibleWhen)}`);
        // Every other property the type declares, carried through generically
        // so registering a property is enough to author *and* generate it
        // (spec 014: a slider's min/max/step arrived this way).
        const declared = componentType(node.type);
        for (const property of Object.keys(declared ? declared.properties : {})) {
            if (["field", "shortKey", "tooltip", "color"].includes(property)) continue;
            if (node[property] === undefined || node[property] === null) continue;
            props.push(`${property}: ${js(node[property])}`);
        }
        // One entry per authored event, so a `change` action does not end up
        // on the click hook the way it did before events had consumers.
        const handlers = [];
        for (const binding of node.bindings || []) {
            if (binding.kind === "visual-state" && binding.state === "highlighted") {
                comments.push(`rule (${binding.source.file}:${binding.source.range?.start.line ?? "?"}) "${binding.conditionText ? `highlighted when ${binding.conditionText} is active` : binding.code}" -> highlighted while ${binding.mockField} === ${js(binding.activeValue)}`);
                props.push(`highlightedWhen: state => state.get(${js(binding.mockField)}) === ${js(binding.activeValue)}`);
            } else if (binding.kind === "visual-state" && binding.state === "disabled") {
                // Spec 050: the first compiler path to disabledWhen (spec
                // 015's own runtime mechanism, synced generically wherever
                // highlightedWhen already is - nothing here or in the
                // renderer needed to change, only this generation).
                comments.push(`rule (${binding.source.file}:${binding.source.range?.start.line ?? "?"}) "disabled unless ${binding.conditionText} is active" -> disabled unless ${binding.mockField} === ${js(binding.activeValue)}`);
                props.push(`disabledWhen: state => state.get(${js(binding.mockField)}) !== ${js(binding.activeValue)}`);
            } else if (binding.kind === "layout-policy") {
                comments.push(`rule "${binding.code}": layout policy ${binding.policy} (expressed by the layout fields above)`);
            } else if (binding.origin === "action" && binding.kind === "command") {
                const action = actions.get(binding.command);
                const event = binding.event || "click";
                comments.push(`action (${binding.source.file}:${binding.source.range?.start.line ?? "?"}) on ${event} -> ${binding.command}, lazy feature actions/${action.moduleName}.js${action.capability ? "" : " (generated mock)"}`);
                handlers.push(`${js(event)}: (app, detail) => app.feature(() => import(${js(`../actions/${action.moduleName}.js`)}), m => m.${action.exportName}(app, detail))`);
            }
        }
        if (handlers.length) props.push(`on: { ${handlers.join(", ")} }`);
        if (selectionModeOf(node.type) === "exclusiveWithinParent" && !(node.bindings || []).some(b => b.origin === "action")) {
            comments.push("no action bound: selecting this item is UI state only (see LOOSE-ENDS.md)");
        }
        const commentLines = comments.map(c => `${pad}// ${c}`).join("\n");
        // Spec 009: one generic factory, called by type name, so the emitter
        // keeps no list of component types and a newly registered type needs
        // no change here. The type name in the generated call is also the
        // authored type, which reads as documentation.
        const call = `component(${js(node.type)}, `;
        const hasChildren = isContainer(node.type);
        let expr;
        if (hasChildren) {
            const rendered = node.children.map(child => nodeExpression(child, depth + 1, indent + 1, moduleImports));
            const childList = rendered.some(r => r.expr) || rendered.some(r => r.comment) ? `[\n${joinEntries(rendered)}\n${pad}]` : "[]";
            expr = `${pad}${call}{ ${props.join(", ")} }, ${childList})`;
        } else if (props.length > 3) {
            expr = `${pad}${call}{\n${props.map(p => `${pad}    ${p}`).join(",\n")}\n${pad}})`;
        } else {
            expr = `${pad}${call}{ ${props.join(", ")} })`;
        }
        return { expr: commentLines ? `${commentLines}\n${expr}` : expr };
    }

    // Joins child entries: real elements are comma-separated, comment-only
    // entries (omitted nodes) are interleaved without commas.
    function joinEntries(entries) {
        const out = [];
        const exprs = entries.filter(e => e.expr);
        let emitted = 0;
        for (const entry of entries) {
            if (entry.comment) { out.push(entry.comment); continue; }
            emitted += 1;
            out.push(entry.expr + (emitted < exprs.length ? "," : ""));
        }
        return out.join("\n");
    }

    for (const [, mod] of uiModules) {
        const node = mod.node;
        const moduleImports = new Set();
        // children are emitted inline; nested panels that have their own
        // module are referenced by their factory
        const props = [`id: ${js(node.id)}`];
        if (node.definitionName) props.push(`name: ${js(node.definitionName)}`);
        // Spec 073: the identical gap spec 025 (breakpoints/visibleWhen) and
        // spec 050 (highlightedWhen/disabledWhen) each already found and
        // fixed once, recurring for label/labelVariants - a module-owning
        // node's own authored `label:` (e.g. a tabPanel item, which always
        // owns its own module since it is itself a panel) was silently
        // dropped by this path, invisible until this spec put one on a
        // module-owning container for the first time (found live: every
        // tab header rendered its own raw node name - "SONGSTAB" - instead
        // of its authored label, "Songs"). Fixed the same way both prior
        // specs did: duplicated here rather than unifying the two
        // node-construction paths, matching nodeExpression()'s own logic
        // exactly (including spec 071's own `label: []` case).
        if (node.labelVariants.length && !(node.definitionName && node.labelVariants.length === 1 && node.labelVariants[0] === node.definitionName)) {
            props.push(`label: ${labelLiteral(node)}`);
        } else if (!node.labelVariants.length && node.definitionName) {
            props.push("label: []");
        }
        const layout = layoutLiteral(node.layout || {});
        if (layout) props.push(layout);
        // Spec 083's own pixel-parity follow-up: the identical gap spec 025
        // (breakpoints/visibleWhen), spec 050 (highlightedWhen/disabledWhen)
        // and spec 073 (label/labelVariants) each already found and fixed
        // once, recurring for a fourth property - a module-owning node's own
        // authored `variant:`/`style:` (menu bar, the first module-owning
        // panel to ever author a non-default one) was silently dropped by
        // this path too, invisible until this spec put one there for the
        // first time (found live: the menu bar's own background rendered
        // with the generic default panel style/asset instead of its real
        // one, with no diagonal-cut artwork at all). Fixed the same way the
        // prior three were: duplicated here rather than unifying the two
        // node-construction paths, matching nodeExpression()'s own logic
        // exactly.
        if (node.style && node.style.variant && node.style.variant !== "default") {
            props.push(`style: ${js(node.style.variant)}`);
        }
        // Spec 025: a module's own root is a node like any other - it can
        // author breakpoints or visibleWhen exactly as controlBar.yaml's own
        // top-level panel now does, so both reach the generated application
        // here too, not only on an inline child (see nodeExpression() above).
        if (node.breakpoints) props.push(`breakpoints: ${js(node.breakpoints)}`);
        if (node.visibleWhen) props.push(`visibleWhen: ${js(node.visibleWhen)}`);
        // Spec 050: the identical gap spec 025 already found and fixed for
        // breakpoints/visibleWhen above, recurring for a different pair of
        // properties - a rule's own highlightedWhen/disabledWhen (generated
        // by nodeExpression() below for an inline child) was never carried
        // through *this* path at all, invisible until this spec put a rule
        // directly on a module-owning container (ftOnlyRow) for the first
        // time. Fixed the same way spec 025 fixed its own pair: duplicated
        // here rather than unifying the two node-construction paths.
        for (const binding of node.bindings || []) {
            if (binding.kind === "visual-state" && binding.state === "highlighted") {
                props.push(`highlightedWhen: state => state.get(${js(binding.mockField)}) === ${js(binding.activeValue)}`);
            } else if (binding.kind === "visual-state" && binding.state === "disabled") {
                props.push(`disabledWhen: state => state.get(${js(binding.mockField)}) !== ${js(binding.activeValue)}`);
            }
        }
        const rendered = node.children.map(child => nodeExpression(child, 1, 2, moduleImports));
        const ruleNotes = (node.bindings || []).map(b => {
            if (b.kind === "layout-policy") return ` * Rule "${b.code}": ${b.policy} (${b.source.file}).`;
            if (b.kind === "visual-state" && b.state === "highlighted") return ` * Rule (${b.source.file}:${b.source.range?.start.line ?? "?"}) "highlighted when ${b.conditionText} is active" -> highlighted while ${b.mockField} === ${js(b.activeValue)}.`;
            if (b.kind === "visual-state" && b.state === "disabled") return ` * Rule (${b.source.file}:${b.source.range?.start.line ?? "?"}) "disabled unless ${b.conditionText} is active" -> disabled unless ${b.mockField} === ${js(b.activeValue)}.`;
            return null;
        }).filter(Boolean);
        const source = `${node.source.file}${node.source.range ? `:${node.source.range.start.line}` : ""}`;
        const useSite = node.refSource ? ` Referenced from ${node.refSource.file}:${node.refSource.range?.start.line ?? "?"}.` : "";
        const text = `// ${GENERATED_HEADER}
import { component } from "${upDirs(1, libraryBase)}runtime/components.js";
${[...moduleImports].sort().map(name => `import { ${name} } from "./${name}.js";`).join("\n")}${moduleImports.size ? "\n" : ""}
/**
 * ${node.definitionName || mod.moduleName} — UI structure generated from ${source}.${useSite}
${ruleNotes.length ? ruleNotes.join("\n") + "\n" : ""} * Behavior lives in ../actions/ (one lazy-loaded module per command); state fields in ../state.js.
 * @returns {object} a component tree for renderers/canvas/mountGeneric.js
 */
export function ${mod.exportName}() {
    return component(${js(node.type)}, { ${props.join(", ")} }, [
${joinEntries(rendered)}
    ]);
}
`;
        files.set(`ui/${mod.moduleName}.js`, text);
    }

    // --- actions (lazy features) ----------------------------------------
    for (const action of actions.values()) {
        const b = action.binding;
        const source = `${b.source.file}:${b.source.range?.start.line ?? "?"}`;
        let body;
        let imports = "";
        if (action.capability) {
            imports = `import { ${action.capability.export} as implementation } from "${upDirs(1, libraryBase)}${action.capability.module.replace(/^\.\//, "")}";\n`;
            body = `/**
 * ${action.command} — generated from ${source}: "${b.code}".
 * Implemented by ${action.capability.module}#${action.capability.export} (mapped in capabilities.js).
 * @param {import("../main.js").AppContext} app
 * @param {object} [detail] what the gesture carried, e.g. { value } for a change
 */
export function ${action.exportName}(app, detail) {
    return implementation(app, detail);
}`;
        } else {
            const field = b.mockField || null;
            const values = Array.isArray(b.mockValues) ? b.mockValues : [];
            body = `/**
 * ${action.command} — generated from ${source}: recipe "${b.code}".
 *
 * GENERATED MOCK: no capability module is mapped for "${action.command}" in
 * capabilities.js, so this only ${field ? `cycles the state field ${js(field)} through ${js(values)}` : "logs the activation"}.
 * Map the command to a hand-written module and rebuild to replace it.
 * @param {import("../main.js").AppContext} app
 * @param {object} [detail] what the gesture carried, e.g. { value } for a change
 */
export function ${action.exportName}(app, detail) {
${field ? `    const values = ${js(values)};
    // A gesture that carries a value says what to store; otherwise the mock
    // cycles the documented values.
    const next = detail && detail.value !== undefined ? detail.value
        : values.length ? values[(values.indexOf(app.state.get(${js(field)})) + 1) % values.length]
        : app.state.get(${js(field)});
    app.state.set(${js(field)}, next);
    app.log(${js(action.command)}, { ${js(field)}: next });` : `    app.log(${js(action.command)}, { ...detail });`}
}`;
        }
        files.set(`actions/${action.moduleName}.js`, `// ${GENERATED_HEADER}\n${imports}\n${body}\n`);
    }

    // --- state --------------------------------------------------------------
    const stateEntries = [...stateFields].map(([field, value]) => `    ${js(field)}: ${js(value)}`);
    files.set("state.js", `// ${GENERATED_HEADER}
import { createAppState as createStore } from "${upDirs(0, libraryBase)}runtime/appState.js";

/**
 * Application state fields and their initial values, collected from every
 * command and visual-state binding in the source. Field paths are the ones
 * the generated actions and UI predicates use.
 */
export const INITIAL_STATE = {
${stateEntries.join(",\n")}
};

/** @returns {ReturnType<typeof createStore>} */
export function createAppState() {
    return createStore(INITIAL_STATE);
}
`);

    // --- skin ----------------------------------------------------------------
    // Spec 008: the generated app carries its own artwork description, in
    // atlas mode (one packed sheet plus one map, written by
    // `node v2/build.mjs skin`). Asset names keep their source PNG path, so
    // the trace from a visual state to the artwork file survives into the
    // release; the authoring-only source ranges are dropped.
    const skinModel = releaseSkinModel(compiled.skin);
    files.set("skin.js", `// ${GENERATED_HEADER}
// The compiled skin: which asset draws which visual state of which component
// style, the 9-slice insets, label placement and font metrics. Development
// loads the individual PNGs named by \`file\`; this release loads the packed
// \`atlas\` pair instead. Source: ${compiled.skin?.source?.file || "built-in fallback skin"}.
export const SKIN = ${JSON.stringify(skinModel, null, 4)};

export default SKIN;
`);

    // --- config, entry, html -------------------------------------------------
    files.set("config.js", `// ${GENERATED_HEADER}
// Location of the skin assets (the packed sheet and its map). The release
// bundle (dist/) swaps this module for one pointing at its copied assets.
export const ASSET_BASE = new URL("${upDirs(0, libraryBase)}assets/skin/", import.meta.url);

// Where non-skin media lives (spec 012: the demo module a capability loads).
export const MEDIA_BASE = new URL("${upDirs(0, libraryBase)}assets/", import.meta.url);
`);

    files.set("main.js", `// ${GENERATED_HEADER}
import { mountGenericRenderer } from "${upDirs(0, libraryBase)}renderers/canvas/mountGeneric.js";
import { createAppState } from "./state.js";
import { ASSET_BASE, MEDIA_BASE } from "./config.js";
import { SKIN } from "./skin.js";
import { main } from "./ui/main.js";

/**
 * @typedef {object} AppContext
 * @property {ReturnType<typeof createAppState>} state
 * @property {(load: () => Promise<any>, run: (module: any) => unknown) => Promise<unknown>} feature loads a lazy feature module, then runs it
 * @property {(command: string, changes: Record<string, unknown>) => void} log
 * @property {URL} media base URL for non-skin media a capability may load
${hostHooks.map(hook => ` * @property {(...args: any[]) => Promise<any>} ${hook.name} host hook, from capabilities.js "${hook.command}"`).join("\n")}
 */

/**
 * Mounts the application into \`container\`. Structure comes from ./ui/*,
 * behavior from ./actions/* (loaded on first use), rendering from the shared
 * canvas runtime. No outline document is fetched.
 * @param {HTMLElement} container
 */
export async function start(container) {
    const state = createAppState();
    /** @type {AppContext} */
    const app = {
        state,
        async feature(load, run) {
            return run(await load());
        },
        log(command, changes) {
            console.info(\`[app] \${command}\`, changes);
        },
        media: MEDIA_BASE${hostHooks.length ? "," : ""}
${hostHooks.map(hook => `        // Host hook "${hook.command}" -> ${hook.capability.module}#${hook.capability.export}.
        // Imported on first use, so nothing it pulls in is in the entry chunk.
        ${hook.name}: (...args) => import("${upDirs(0, libraryBase)}${hook.capability.module.replace(/^\.\//, "")}").then(m => m.${hook.capability.export}(app, ...args))`).join(",\n")}
    };
    const result = await mountGenericRenderer(container, { root: main(), diagnostics: [], skin: SKIN }, {
        tools: false,
        state,
        appContext: app,
        assetBase: ASSET_BASE
    });
    // Boot-time default content (spec 081, deep-parity-audit item 8): matches
    // v1's own real \`script/src/editor.js#loadInitialFile\`, which populates
    // the sidebar's Songs tab with a curated demo list immediately on load.
    // Lazy-imported the same way every host hook above is, so nothing it
    // pulls in enters the entry chunk; fire-and-forget after mounting, not
    // awaited, so a slow/failed fetch never delays the app's own first paint.
    import("${upDirs(0, libraryBase)}domain/playlist/index.js").then(m => m.loadDefaultSongs(app)).catch(error => console.error("[app] failed to load default songs", error));
    // Boot-time default module: loads (but does not play) the same curated
    // demo tune v1 loads on startup (script/src/editor.js#loadInitialFile's
    // real default, "demomods/Tinytune.mod"), so the tracker isn't empty on
    // first paint. Fire-and-forget, same pattern as loadDefaultSongs above.
    import("${upDirs(0, libraryBase)}domain/playback/index.js").then(m => m.loadModule(app, "demomods/Tinytune.mod")).catch(error => console.error("[app] failed to load default module", error));
    return result;
}
`);

    files.set("index.html", `<!doctype html>
<!-- ${GENERATED_HEADER} -->
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>BassoonTracker v2</title>
<style>
  html, body { margin: 0; height: 100%; background: #111; color: #ccc; font: 12px monospace; }
  #app { position: absolute; inset: 0; }
  #status { position: absolute; inset: 0; display: flex; align-items: center; justify-content: center; padding: 16px; text-align: center; white-space: pre-wrap; }
</style>
</head>
<body>
<div id="status">Loading…</div>
<div id="app"></div>
<script type="module">
  import { start } from "./main.js";
  start(document.getElementById("app")).then(() => document.getElementById("status").remove()).catch(error => {
    console.error(error);
    document.getElementById("status").textContent = "Failed to start:\\n" + error.message;
  });
</script>
</body>
</html>
`);

    // --- documents ----------------------------------------------------------
    const grouped = new Map();
    for (const e of looseEnds) {
        if (!grouped.has(e.kind)) grouped.set(e.kind, []);
        grouped.get(e.kind).push(e);
    }
    const looseEndsMd = `# Loose ends

${GENERATED_HEADER}

${looseEnds.length === 0 ? "None: every authored node and binding was resolved." : `${looseEnds.length} item(s). Per policy (spec 007) none of these fail the build; each was handled as listed and should be resolved in the YAML source, a recipe, or a capability module.`}

| kind | subject | source | what the build did |
|---|---|---|---|
${looseEnds.map(e => `| ${e.kind} | ${e.subject.replace(/\|/g, "\\|")} | ${e.where} | ${e.did} |`).join("\n")}
`;
    files.set("LOOSE-ENDS.md", looseEndsMd);

    const readme = `# Generated application

${GENERATED_HEADER}

Compiler ${COMPILER_VERSION}${compiled.sourceHash ? `, source hash \`${compiled.sourceHash.slice(0, 12)}\`` : ""}. Sources: ${[...compiled.sourceFiles].sort().map(f => `\`${f}\``).join(", ")}.

## Layout

| path | role |
|---|---|
| \`index.html\` | mounts the app; run from any static host that serves the v2 folder |
| \`main.js\` | entry: creates state, the app context (lazy feature loader, log) and mounts the canvas renderer |
| \`ui/*.js\` | one module per authored container: ${[...uiModules.values()].map(m => `\`${m.moduleName}\``).join(", ")}. Structure only; each leaf carries its behavior as a reference into \`actions/\` or a state predicate |
| \`actions/*.js\` | one lazy-loaded module per command: ${[...actions.values()].map(a => `\`${a.moduleName}\` (${a.command}${a.capability ? "" : ", mock"})`).join(", ") || "none"} |
| \`state.js\` | the state fields and initial values every action and predicate uses |
| \`skin.js\` | the compiled skin: asset per visual state per component style, insets, label placement, font metrics, in atlas mode |
| \`config.js\` | asset location; replaced by the release bundle |
| \`LOOSE-ENDS.md\` | everything the source left unresolved and how this build handled it |

Shared library (not generated): \`${libraryBase}/runtime/\` (components, state, layout, controllers) and \`${libraryBase}/renderers/canvas/\` (drawing, hit-testing, mounting).

## Replacing a mock

Add an entry to \`v2/capabilities.js\`, for example \`"transport.toggle": { module: "./domain/transport.js", export: "togglePlay" }\`, and rebuild. The action module then imports and delegates to your code; the app context it receives has \`state\` (get/set/subscribe) and \`log\`.
`;
    files.set("README.md", readme);
    files.set(".generated", "This folder is produced by `node v2/build.mjs app`; everything in it is overwritten on rebuild.\n");

    return { files, looseEnds, actions: [...actions.values()], uiModules: [...uiModules.values()].map(m => m.moduleName), stateFields: Object.fromEntries(stateFields) };
}
